//! Модуль «Коммуникации»: личные диалоги и групповые чаты сотрудников.
//!
//! Правила (журнал решений D-020…D-086):
//! - модуль отдельный от заявок, пользоваться может любой вошедший сотрудник;
//! - текст сообщений и их прежних версий хранится зашифрованным ключом портала; штатно читают только
//!   участники — ни администратор, ни суперадминистратор чужую переписку не читают. Суперадминистратор
//!   видит только обезличенную статистику по порталу в целом и может назначить владельца группового чата
//!   (в том числе себя) — это попадает в аудит;
//! - сообщения не удаляются; автор правит своё сообщение 15 минут, прежние версии сохраняются;
//! - состав группового чата ведут владелец и администраторы чата; добавление и исключение — сразу,
//!   с уведомлением; в ленте о составе ничего не пишется, есть отдельная история состава;
//! - вышедший или исключённый читает историю до момента выхода, писать не может; вернувшийся и новый
//!   участник видят всю историю;
//! - учётка отключена в AD — сотрудник выбывает из групповых чатов; владение переходит самому давнему
//!   администратору, а если его нет — чат блокируется до назначения владельца суперадминистратором.

pub mod api;
pub mod sweep;

use pult_core::Permission;

pub use sweep::{SWEEP_JOB, sweep_blocked};

/// Модуль для сервера: маршруты. Особых разрешений нет — чаты доступны всем вошедшим,
/// администрирование — суперадминистратору.
pub struct ChatModule;

impl<S> pult_core::Module<S> for ChatModule
where
    S: Clone + Send + Sync + 'static,
    pult_core::Core: axum::extract::FromRef<S>,
{
    fn name(&self) -> &'static str {
        "chat"
    }

    fn routes(&self) -> utoipa_axum::router::OpenApiRouter<S> {
        api::routes()
    }

    fn permissions(&self) -> Vec<Permission> {
        Vec::new()
    }
}

/// Виды уведомлений модуля.
pub mod kind {
    /// Вас добавили в групповой чат.
    pub const ADDED: &str = "chat.added";
    /// Вас исключили из группового чата.
    pub const REMOVED: &str = "chat.removed";
    /// Вы стали владельцем группового чата.
    pub const OWNER: &str = "chat.owner";
    /// Суперадминистратор назначил чату нового владельца (остальным участникам).
    pub const OWNER_CHANGED: &str = "chat.owner_changed";
    /// Чат без владельца заблокирован (суперадминистраторам).
    pub const LOCKED: &str = "chat.locked";
    /// Чат снова доступен (всем участникам).
    pub const UNLOCKED: &str = "chat.unlocked";
}
